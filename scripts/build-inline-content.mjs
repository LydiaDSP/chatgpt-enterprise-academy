import {readFileSync, writeFileSync} from 'node:fs';
const read = path => readFileSync(new URL('../' + path, import.meta.url), 'utf8').replace(/\r\n/g,'\n');
const content = {};
for (const name of ['multimedia', 'roles']) {
  const html = read('labs/' + name + '.html');
  let body = html.match(/<main class="wrap">([\s\S]*?)<\/main>/)[1];
  // Resolve standalone relative links before embedding in the root page.
  body = body.replace(/href="([^"#][^"]*)"/g, (match, href) => {
    if (/^https?:/.test(href)) return match;
    return 'href="' + (href.startsWith('../') ? href.slice(3) : 'labs/' + href) + '"';
  });
  if (name === 'roles') {
    body = body.slice(body.indexOf('<section id="role-IE"'));
    body = body.replace(/<footer[\s\S]*?<\/footer>/, '');
    body = '<span id="countIE" hidden></span><span id="countIT" hidden></span>' + body;
  } else {
    body = body.replace(/<section class="hero">[\s\S]*?<\/section>/, '');
    body = body.replace(/<label><input id="teacher"[\s\S]*?<\/label><label><input id="large"[\s\S]*?<\/label>/, '<input id="teacher" type="checkbox" hidden><input id="large" type="checkbox" hidden>');
  }
  content[name] = {html: body, css: read('labs/lab.css') + (name === 'multimedia' ? read('labs/multimedia.css') : '')};
}
const generated='// Generated by scripts/build-inline-content.mjs; edit the source labs instead.\nwindow.ACADEMY_INLINE = '+JSON.stringify(content)+';\n';
if(process.argv.includes('--check')){
  if(read('inline-content.js').replace(/\r\n/g,'\n')!==generated.replace(/\r\n/g,'\n'))throw Error('Run node scripts/build-inline-content.mjs to update the offline content bundle.');
}else writeFileSync(new URL('../inline-content.js', import.meta.url),generated);
